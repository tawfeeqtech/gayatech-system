async function seed() {
  try {
    await mongoose.connect(process.env.MONGODB_URI || 'mongodb://localhost:27017/gayatech');
    console.log('✅ متصل بقاعدة البيانات');

    let countryCount = 0, cityCount = 0;

    for (const [countryName, cityNames] of Object.entries(locations)) {
      let country = await Country.findOne({ name: { $regex: `^${countryName}$`, $options: 'i' } });
      if (!country) {
        country = await Country.create({ name: countryName, createdBy: null });
        countryCount++;
        console.log(`   🌍 ${countryName}`);
      } else {
        console.log(`   ⏭️  ${countryName} — موجود`);
      }

      for (const cityName of cityNames) {
        const existing = await City.findOne({
          name: { $regex: `^${cityName}$`, $options: 'i' },
          country: country._id,
        });
        if (!existing) {
          await City.create({ name: cityName, country: country._id, createdBy: null });
          cityCount++;
        }
      }
    }

    console.log(`\n📊 تمت إضافة ${countryCount} دولة و ${cityCount} مدينة جديدة`);
    await mongoose.disconnect();
    process.exit(0);
  } catch (err) {
    console.error('❌ خطأ:', err.message);
    process.exit(1);
  }
}

seed();
